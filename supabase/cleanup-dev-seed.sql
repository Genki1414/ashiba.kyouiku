-- 開発用の種データを消す（本番で1回だけ流す）
--
-- supabase/seed.sql で入れた5行を消す。
--   ・受講テスト（dev@example.invalid）      … ログインできない、記録の置き場
--   ・注文 1名・0円・請求書                  … 買った覚えのない注文として画面に出る
--   ・受講コード DEV-0001                    … 7文字なので、そもそも入れられない
--
-- 事業者（22222222-…）は消さない。
-- 最初の /setup で名前を付け替えたので、いまは本物の事業者になっている。
-- 消すと、その会社の受講者・注文・修了証が全部いなくなる。
--
-- 流したあと /owner を見ると、0円の注文が消えている。
-- ═══════════════════════════════════════════════════════════

begin;

-- 受講とその記録（視聴・小テスト・修了試験・実務・修了証は cascade で一緒に消える）
delete from public.enrollments
 where id = '55555555-5555-5555-5555-555555555555';

-- 受講コードと注文
delete from public.seats  where id = '44444444-4444-4444-4444-444444444444';
delete from public.orders where id = '33333333-3333-3333-3333-333333333333';

-- 開発用の受講者（ログインの行も一緒に）
delete from public.users where id = '11111111-1111-1111-1111-111111111111';
delete from auth.users   where id = '11111111-1111-1111-1111-111111111111';

-- 念のため確かめる。0 が3つ並べば消えている
select
  (select count(*) from public.orders where id = '33333333-3333-3333-3333-333333333333') as 注文,
  (select count(*) from public.seats  where id = '44444444-4444-4444-4444-444444444444') as 受講コード,
  (select count(*) from public.users  where id = '11111111-1111-1111-1111-111111111111') as 受講者;

commit;
