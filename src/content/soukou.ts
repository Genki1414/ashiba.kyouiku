/* 走行集材機械の運転の業務の特別教育。

   走行集材機械は、**丸太を荷台に載せて、作業道を走って運ぶ機械**。
   フォワーダ、集材車。荷台とグラップルクレーンが付き、ウインチで木を引き寄せるものもある。
   伐木等機械（切る・造材する・集める）とは別の教育。**この教育でハーベスタは動かせない。**
   道路の上を走らせる運転は除く（道路交通法の話）。

   科目・範囲・時間は
   **安全衛生特別教育規程（昭和47年労働省告示第92号）第8条の3**のまま。
   学科6時間（1／1／2／1／1）＋実技6時間（走行3／作業装置3）。
   条文の表は、げんきさんが送ってくれた全文で確認済み（2026年9月3日）。
   条文の末尾に「(平二五厚労告三六三・追加)」とある。伐木等機械と同じ告示で足された。
   裏取りは docs/50-走行集材機械の根拠と裏取り.md。

   伐木等機械（第8条の2）と科目の形は同じだが、二つ違う。
   ・科目4の中欄に**「ワイヤロープの種類及び取扱いの方法」**が足されている（ウインチで引くから）
   ・実技が**走行3時間・作業装置3時間**（伐木等機械は2／4）。走る機械だから走行が長い

   **この機械で人が死ぬ形は、荷を載せた機械の転倒・転落（作業道の路肩・傾斜）、
   積込み中のグラップルと丸太、ウインチのワイヤ。**軸は三つ。
   ・荷を載せれば重心が高くなる。傾斜は登り下りまっすぐ、路肩に寄らない、積載量を守る
   ・積込みと荷下ろしのとき、グラップルの届く範囲と丸太の転がる範囲に人を入れない
   ・ウインチのワイヤの内側と、引く方向の延長に人を入れない

   ここは何にも依存しない。単体で持ち出せるようにしてある。 */

