/* 特定線量下業務の特別教育（目録62）。

   科目・範囲・時間は
   **除染等業務特別教育及び特定線量下業務特別教育規程
   （平成23年厚生労働省告示第469号）第5条**のまま。
   **告示の全文で、科目名・中欄・時間を一字ずつ確かめてある**（2026年9月5日・docs/73）。
   **学科2時間30分だけ。実技は無い。**
   根拠は**除染則（東日本大震災により生じた放射性物質により汚染された土壌等を
   除染するための業務等に係る電離放射線障害防止規則・平成23年厚生労働省令第152号）
   第25条の8第1項**。裏取りは docs/81。

   **除染等業務（目録61）とは別の業務。**
   除染等業務は「汚染された土などを、除染する・集める・運ぶ」仕事。
   **特定線量下業務は、除染をしない。**
   **決められた線量より高い場所で、ふつうの仕事をする**業務。
   建物を建てる、道を直す、店を開ける、電気やガスを引く——
   **仕事の中身は変わらないが、場所の線量が高い。**

   **だから、この講座は「その場所で働くこと」を教える。**
   除染の機械の話も、汚染の除去の話も、告示の中欄に入っていない。

   **除染等業務（61）と違って、業務区分が無い。**
   61 は五つの区分で時間が変わるが、**この62は一本。**
   そのままひとつの講座にできる（docs/73）。

   **うちの講座でいちばん短い。**学科150分。
   短いということは、**その分だけ、外さないところを外さない**ということ。

   **軸は三つ。**
   ・**自分の被ばく線量を、自分で知る。**測る・見る・記録が残る
   ・**線量は場所で変わる。**同じ現場でも、側溝や雨どいの下は高い
   ・**異常な事態が起きたときに、何をするか**（中欄に名指しである）

   ここは何にも依存しない。単体で持ち出せるようにしてある。 */

