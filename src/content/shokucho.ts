/* 職長教育（職長・安全衛生責任者教育）の科目と時間。

   根拠：労働安全衛生法第60条／労働安全衛生規則第40条
   法定：合計12時間以上

   特別教育（安衛法59条3項）とは別の制度で、
   **討議方式**が原則という点が決定的に違う。
   録画を見せるのは討議にならない。
   この仕組みでは、同じ時間に集まってやり取りする
   オンラインの討議（同時双方向）で行う。

   時間の持ち方：
     科目ごとに「講義」「討議」「演習」を分けて持つ。
     3つの合計が、その科目の法定最低時間を下回ってはいけない。
     下回っていれば公開できない（src/lib/hours.ts）。

   ── 細目 ──
   科目の下に、法定の細目がある（安衛則第40条第2項の表の左欄）。
   単元は、この細目に1つずつ対応させる。
   対応させておくと、12時間ぶんの中身がそろっているかを、
   元請にも監督署にも、そのまま示せる。
   どこで確かめたかは docs/18-職長教育の根拠と裏取り.md。

   ここに書いてあるのは**法定の最低**と、初期の割り振り。
   割り振りは本部の画面から変えられるようにする（合計が下回らない範囲で）。

   ── 討議は講座に1回だけ ──
   科目ごとに討議を置くと、5回も日を合わせて集まることになる。
   受ける人にも講師にも重すぎるので、**45分の回を1度だけ**にした。
   その45分は12時間の中に入り、TALK_SUBJECT の科目の時間として数える。
   討議は Zoom でやる（URLは回ごとに登録する）。 */

export type TalkKind = "case" | "drill" | "none";

export type ShokuchoSubject = {
  id: number;
  /** 法令の科目名。そのまま修了証に載る */
  name: string;
  /** 法定の細目（安衛則第40条第2項の表の左欄）。
      単元は、この細目に1つずつ対応させる。
      対応させておくと、「12時間ぶんの中身がそろっているか」を
      元請にも監督署にも、そのまま示せる */
  saimoku: string[];
  /** 法定の最低時間（分）。ここは動かさない */
  legalMin: number;
  /** 教える中身 */
  topics: string[];
  /** 討議の型。case=事例研究 drill=演習 */
  talk: TalkKind;
  /** 討議のお題（受講者に出す） */
  talkQuestion: string;
  /** 初期の割り振り（分）。合計は legalMin 以上 */
  plan: { lecture: number; talk: number; drill: number };
};

export const SHOKUCHO_TOTAL_MIN = 720; // 職長教育の12時間

/* ── 安全衛生責任者教育の2時間 ──────────────

   建設業では、職長教育（12時間）に安全衛生責任者教育（2時間）を足して、
   **14時間**で「職長・安全衛生責任者教育」として実施するのが普通。
   講座の名前をそう付けている以上、この2時間が要る。

   前は12時間だけで組んでいた。
   その状態で「職長・安全衛生責任者教育」の修了証を出すと、
   受けていない教育の名前が紙に載ることになる。

   中身は統括安全衛生管理の進め方。
   混在作業、作業間の連絡調整、安全施工サイクル。
   法定の細目ではなく、安衛法第16条・安衛則第19条の職務から来ている。 */
export const SEKININSHA_MIN = 120; // 2時間

/** 講座ぜんぶ。修了証に載る時間 */
export const COURSE_TOTAL_MIN = SHOKUCHO_TOTAL_MIN + SEKININSHA_MIN; // 840分＝14時間

