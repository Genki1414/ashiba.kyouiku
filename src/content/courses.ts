export type CourseMeta = {
  /** URL とデータベースで使う目印。あとから変えない */
  id: string;
  /** 教育の種類。書かなければ特別教育 */
  kind?: CourseKind;
  /** 進み方。書かなければ各自でいつでも（ondemand） */
  type?: CourseType;
  /** 学科のあとに残る関門。書かなければ無し（学科だけで修了） */
  gate?: CourseGate;
  /** 実技の法定時間（分）。gate: "drill" の講座だけ。

      受ける人に「学科のあとに何時間残るか」を先に出すために要る。
      画面に「3時間」と書き込むと、次の実技のある講座で嘘になる。 */
  drillMin?: number;
  /** 正式名称。修了証に載る */
  name: string;
  /** 画面で使う短い呼び名 */
  short: string;
  /** 法令の根拠 */
  basis: string;
  /** 学科の法定時間（分） */
  totalMin: number;
  /** 教材の json（content/courses/ の中） */
  file: string;
  /** 受講できるか。教材がまだなら false（画面には「準備中」と出る） */
  ready: boolean;
  /** 一覧のどこに出すか。

      "main" … そのまま並べる（既定）
      "other" … 「その他特別教育」を開いてから選ぶ

      特別教育は種類が増える。全部そのまま並べると、
      足場を受けに来た人が長い一覧から探すことになる。
      これから足す特別教育は "other" にする。
      見出しが「その他特別教育」なので、ここへ入れてよいのは
      特別教育（kind: "special"）だけ。 */
  menu?: CourseMenu;
};

