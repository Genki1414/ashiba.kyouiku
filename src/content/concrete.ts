/* 車両系建設機械（コンクリート打設用）の作業装置の操作の業務の特別教育。

   コンクリートポンプ車など、**生コンを圧送して打つ機械**の作業装置を操作する仕事。

   科目・範囲・時間は
   **安全衛生特別教育規程（昭和47年労働省告示第92号）第12条の2**のまま。
   学科7時間（4／2／1）＋実技5時間（作業装置の操作4／運転のための合図1）。
   条文の表は、げんきさんが送ってくれた全文で確認済み（2026年9月3日）。
   条文の末尾に「(平二労告五四・追加)」とある。平成2年の告示で足された条。
   裏取りは docs/57-コンクリート打設用機械の根拠と裏取り.md。

   **これは「運転」の教育ではない。「作業装置の操作」の教育。**
   基礎工事用の第11条の5と同じ形で、
   告示の科目も実技も、**作業装置の操作**と**合図**でできている。
   **車を走らせる運転は、道路交通法の免許の話。**別。

   **対象は「安衛則第36条第10号の2に掲げる機械」。**
   告示の中欄も「車両系建設機械（コンクリート打設用）（安衛則第三十六条第十号の二の機械をいう。以下同じ。）」
   と書くだけで、**どの機械が当たるかは安衛則の側にある。**
   **その安衛則第36条第10号の2の条文は、まだ確かめていない。**
   だからこの講座では、**当たる機械の範囲を条文の字で言い切っていない。**
   「自分の機械がこの教育の対象かは、会社と機械のメーカーに確かめる」と単元に書いてある。

   **科目2の中欄が、この教育だけ違う。**
   ほかの車両系は「力学**及び土質工学**／土木施工の方法／ワイヤロープ及び補助具」だが、
   ここは**「力学／コンクリートの種類及び性質／コンクリート打設の方法」。**
   **土でもワイヤでもなく、コンクリートそのものを知れ**という科目になっている。
   生コンの性質が、詰まりも、圧力も、打設の段取りも決めるから。

   **この仕事で人が死ぬ形は、ブームの転倒（アウトリガ）、輸送管の閉塞と破裂、
   先端ホースの振れ、架空電線、打設中の型枠の倒壊、生コンによる目と皮膚の傷害。**軸は三つ。
   ・**アウトリガ。ブームを伸ばせば重心が外へ出る。**張り出し不足と敷板の無さが転倒の元
   ・**閉塞（詰まり）。圧を抜かずに管を開けない。**先端ホースを人に向けない
   ・**上を見る（架空電線）。合図者を決める。**ブームは高く、打設の先は運転者から見えない

   ここは何にも依存しない。単体で持ち出せるようにしてある。 */

