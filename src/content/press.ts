/* 動力プレスの金型、シヤーの刃部又はプレス機械若しくはシヤーの安全装置若しくは安全囲いの
   取付け、取外し又は調整の業務の特別教育。

   **プレスを「打つ」教育ではない。金型を「付ける・外す・合わせる」教育。**
   安衛則第36条第2号は、動力プレスの**金型等の取付け、取外し又は調整**の業務を
   特別教育の対象にしている。普段の打ち抜き作業そのものは対象ではないが、
   型を替える人、刃を替える人、安全装置を合わせる人は必ず受ける。

   科目・範囲・時間は
   **安全衛生特別教育規程（昭和47年労働省告示第92号）第3条**のまま。
   学科8時間（2／2／3／1）＋実技2時間。
   条文の表は、げんきさんが送ってくれた全文で確認済み（2026年9月3日）。
   条文の末尾に「(昭五二労告一一七・一部改正)」とある。
   裏取りは docs/47-動力プレスの根拠と裏取り.md。

   **この教育でいちばん多い事故は、手指の挟まれと切断。**
   金型の間（危険限界）に手を入れたままスライドが降りる。
   だから軸は三つ。
   ・型替えのときは**スライドを止めて、安全ブロック**を入れる
   ・材料が詰まっても、**手を入れる前に止める**
   ・安全装置は**機械のクラッチの種類と、金型に合わせて**選び、合わせ直す

   告示の字「シヤー」「シヤーの刃部」はそのまま。
   ここは何にも依存しない。単体で持ち出せるようにしてある。 */

