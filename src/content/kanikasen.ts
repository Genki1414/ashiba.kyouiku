   二つの機械が一つの教育になっている。
   ・**簡易架線集材装置**……主索を張らない（または簡単な）架線で、集材機とワイヤロープで
     原木を引き寄せて集める仕掛け。機械集材装置（第9条）の「簡易」な形。
     搬器を主索で走らせる本式の架線ではなく、**引き寄せる**のが中心
   ・**架線集材機械**……スイングヤーダのように、**自分で走って移動し、ウインチで集材する機械**。
     ベースマシンにウインチとブーム（またはタワー）が付いている

   だから科目が両方に分かれている。走行の話（架線集材機械）と、
   索張り・集材の話（簡易架線集材装置）と、両方に共通のワイヤロープ。

