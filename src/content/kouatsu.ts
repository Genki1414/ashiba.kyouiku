   対象は、**高圧若しくは特別高圧の充電電路又はその支持物の
   敷設、点検、修理又は操作の業務**（安衛則第36条第4号のうち高圧・特別高圧の分）。

   科目・範囲・時間は
   **安全衛生特別教育規程（昭和47年労働省告示第92号）第5条**のまま。
