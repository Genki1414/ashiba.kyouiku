/* 石綿の特別教育の科目・範囲・時間。

   正式には**石綿使用建築物等解体等業務特別教育**。
   現場では「石綿取扱い作業従事者特別教育」「アスベスト特別教育」とも呼ぶ。

   根拠：
     労働安全衛生法 第59条第3項
     労働安全衛生規則 第36条第37号
     石綿障害予防規則 第27条第1項
     石綿使用建築物等解体等業務特別教育規程（平成17年厚生労働省告示第132号）

   法定：**学科のみ 合計4時間30分以上。実技は無い。**
   だから、この仕組みだけで修了証まで出せる（足場と同じ）。

   ── 告示の言い方 ──
   「次の表の上欄に掲げる科目に応じ、それぞれ、同表の中欄に掲げる範囲について
     同表の下欄に掲げる**時間以上**行うものとする」

   **「時間以上」なので、下回ってはいけないが、上回るのは構わない。**
   単元ごとの視聴時間の関門は、この表のとおりに置く。
   教材が表より長くなるぶんには問題ない。短くしないこと。

   ── 科目名と範囲は、告示のまま ──
   言い換えると突き合わせられなくなる（docs/19）。
   条文に著作権は無い（著作権法第13条）ので、ここは写してよい。
   写さないのは、テキストの解説文のほう。

   ── 調べ直したときの経緯 ──
   web で見つかる資料では**保護具が 0.5時間 と 1時間 で食い違っていた。**
   合計は4時間30分で一致していたので、内訳が合わないまま進みかけた。
   告示の表を見て、**保護具は1時間**と決まった。
   0.5時間で作っていたら、その科目だけ法定の半分で先へ進めていた。
   **「合計が合っているから大丈夫」は通らない。関門は科目ごとに掛かる。**
   裏取りの記録は docs/25-石綿の根拠と裏取り.md。 */

