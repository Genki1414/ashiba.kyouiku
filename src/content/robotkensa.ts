/* 産業用ロボットの可動範囲内で検査等を行う業務の特別教育。

   **ロボットの可動範囲の中に入って、検査・修理・調整をする仕事**の教育。
   保全と生産技術、メーカーとサービスの技術者、設備の担当者。

   科目・範囲・時間は
   **安全衛生特別教育規程（昭和47年労働省告示第92号）第19条**のまま。
   学科9時間（4／4／1）＋**実技4時間**（操作1時間・検査等の作業3時間）。
   条文の表は、げんきさんが送ってくれた全文で確認済み（2026年9月4日）。
   条文の末尾に「(昭五八労告四九・追加)」とある。昭和58年の告示で足された条。
   **教示等（第18条）と同じ告示で、同時に足されている。**

   **条文の字は「産業用ロボツト」**（ツが大きい）。告示の古い書き方のまま。
   **範囲（中欄）を引くところは、条文の字のままにしてある。**
   解説の中では、読みやすさのために「ロボット」と書いている。

   **対象は「安衛則第36条第32号に掲げる業務」。**
   告示は号を引用するだけで、**どの作業が当たるかは安衛則の側にある。**
   **その安衛則第36条第32号の条文は、まだ確かめていない。**
   だからこの講座では、**当たる作業の範囲を条文の字で言い切っていない。**
   「自分の仕事がこの教育の対象かは、会社に確かめる」と単元に書いてある。

   **隣に、教示等の教育がある。**
   **教示等**（規程第18条／安衛則第36条第31号）。学科7時間＋実技3時間。
   **検査等（この教育）と教示等は、別の教育。**両方やる人は、両方要る。

   **教示等との、いちばん大きな違い。**
   **科目1が2時間ではなく4時間で、中欄に「制御方式」「駆動方式」「各部の構造」
   「制御部品の種類及び特性」が入っている。**
   **中を開けて、部品を触る仕事だから**、機械の中身を深く求めている。

   **この仕事で人が死ぬ形は、可動範囲の中での挟まれと激突、
   そして「電気を切ったのに動いた」。**軸は三つ。
   ・**中を開ける仕事。**カバーを外し、部品を外し、電気を触る
   ・**電気を切っても、まだ動く。**ブレーキの解除で腕が落ちる。残圧、ばね、蓄えた電気
   ・**直したあとが、いちばん危ない。**戻し忘れ、無効にしたまま、試運転

   ここは何にも依存しない。単体で持ち出せるようにしてある。 */

