/* 認証メール（合言葉の決め直し・登録の確認）の差出人。

   受け取る側にはこう見える。送ったあとの画面で、先に同じものを見せておく。
   受信箱で探すとき、迷惑メールに入っていたとき、どれを見ればいいかが分かる。

   ── なぜ画面に出すか ──
   もとは Supabase の共用送信元（noreply@mail.app.supabase.io）から
   英語で届いていた。知らない英語の差出人から「パスワードを再設定しろ」と
   リンクが来る形は、迷惑メールの見分け方として教わるものと同じで、
   押してもらえなければ、忘れた人はそこで詰まる。
   だから「こういう差出人から届きます」と先に伝えることにした。

   いまは自前の送信元（Resend 経由の noreply@ashibase.jp）になったので、
   詐欺メールに見える問題は無い。それでも差出人は出しておく。
   迷惑メールに振り分けられたときに、探す手がかりになる。

   ── 変えるとき ──
   送信元を変えたら、ここの2つを直すこと。直し忘れると、
   画面に嘘の差出人が出たままになる（/setup にも出している）。
   AUTH_MAIL_FROM を空文字にすれば、画面の案内も /setup の行も消える。 */

/** 認証メールの差出人。受信箱にこう出る */
export const AUTH_MAIL_FROM = "足場屋革命 <noreply@ashibase.jp>";

/** 自前の送信元か。false だと Supabase の共用送信元（英語・1時間に数通まで） */
export const AUTH_MAIL_OWN = true;

/** 差出人の案内を出すか */
export const showMailFrom = (): boolean => AUTH_MAIL_FROM.trim().length > 0;

/** 送ったあとの画面に添える一言 */
export const mailFromNote = (): string =>
  AUTH_MAIL_OWN
    ? "迷惑メールに入っていたときは、この差出人で探してください。"
    : "英語のメールで届くことがあります。こちらから送ったものなので、そのままリンクを押して構いません。";
