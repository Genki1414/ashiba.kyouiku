/** いちばん新しい目印 */
export const LATEST = RELEASES[0].v;

/** いちばん新しい日ぶん。初めての人に、その日の分だけまとめて見せる */
function newestDay(releases: Release[]): Release[] {
  if (!releases.length) return [];
  return releases.filter((r) => r.d === releases[0].d);
}

/**
 * まだ見ていない更新を返す。
 * - 初めて開いた人（seen が無い）には、いちばん新しい日ぶんだけ。
 *   ここまでの全部を出すと長すぎて読まれない
 * - 前に見た目印より新しいものを、上から順に
 * - 目印が分からないとき（消した・古すぎる）も、いちばん新しい日ぶんだけ
 */
export function unseen(seen: string | null, releases: Release[] = RELEASES): Release[] {
  if (!seen) return newestDay(releases);
  const i = releases.findIndex((r) => r.v === seen);
  if (i < 0) return newestDay(releases);
  return releases.slice(0, i);
}
