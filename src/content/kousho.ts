/* 高所作業車の運転の業務に係る特別教育の科目・範囲・時間。

   対象は**作業床の高さが10メートル未満**の高所作業車。
   10メートル以上は技能講習で、別の制度。

   根拠：
     労働安全衛生法 第59条第3項
     労働安全衛生規則 第36条第10号の5
     安全衛生特別教育規程 第13条

   法定：**学科6時間 ＋ 実技3時間。**

   ── 石綿と決定的に違う ──
   **実技が3時間ある。この仕組みだけでは修了しない。**
   実技は実機が要るので、事業者が自社で行う。
   学科が終わったら本人が発行申請を出し、そのとき実技の実施日と実施者を書く。
   本部がそれを見て通して、はじめて修了（courses.ts の gate: "drill"）。

   **学科だけで修了証を出せば、実技を受けていない人が
   「資格がある」と思って高所作業車に乗る。**

   ── 告示の言い方 ──
   「同表の下欄に掲げる**時間以上**行うものとする」
   下回ってはいけないが、上回るのは構わない。

   ── 科目名と範囲は、告示のまま ──
   言い換えると突き合わせられなくなる（docs/19）。
   裏取りの記録は docs/26-高所作業車の根拠と裏取り.md。

   ── 調べたときの経緯 ──
   web で見つかる資料からは、科目ごとの時間が取れなかった。
   こちらの見当では「装置1時間・原動機3時間」だったが、
   告示の表は**逆で「装置3時間・原動機1時間」**だった。
   推測で埋めていたら、装置の科目が法定の3分の1になっていた。 */

