/* 教材の章立ての出どころ。講座を足すたびに、ここに1件足す。

   ── なぜ要るか ──
   教材の章立てを、こちらの頭だけで決めると必ずずれる。
   法定の科目に無いものを入れてしまったり、
   逆に細目が抜けたまま12時間ぶんを作ってしまったりする。
   売り物なので、それは通らない。

   だから決まりを1つ置く。

     **章立ては、必ず「法令の細目」と「公開されている講習の章立て」から作る。**
     完全な自作はしない。ただし、文章はそのまま写さない。

   条文には著作権が無い（著作権法第13条）ので、細目の言い回しはそのまま使える。
   一方、テキストの解説文には著作権がある。だから章立て（どの順で何を扱うか）
   だけを参考にして、中身は書き下ろす。

   この決まりは、これから足す特別教育にも同じように当てはめる。
   docs/19-教材の章立ての決まり.md */

